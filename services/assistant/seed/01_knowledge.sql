Что такое академическая задолженность
Академическая задолженность — это оценка «неудовлетворительно» или «не зачтено» на экзамене или зачёте, а также неявка без уважительной причины. Задолженность не означает отчисления: у студента есть время её ликвидировать.

Сколько раз можно пересдавать
Пересдать дисциплину можно не больше двух раз в сроки, которые назначил деканат. Первая пересдача проходит у преподавателя, который вёл дисциплину. Вторая пересдача проходит перед комиссией из трёх преподавателей кафедры, её оценка окончательная.

Сроки пересдач
Деканат публикует расписание пересдач не позже чем через неделю после окончания сессии. Задолженности за зимнюю сессию нужно ликвидировать до 1 марта, за летнюю — до 1 октября. Во время каникул пересдачи не проводятся.

Как записаться на пересдачу
Записываться заранее не нужно: даты пересдач появляются в расписании кабинета и в уведомлениях. Если пересдача совпала с другим экзаменом или вы не можете прийти по уважительной причине, до даты пересдачи подайте в кабинете заявку «Вопрос в деканат» и приложите подтверждающий документ.

Если вы болели во время сессии

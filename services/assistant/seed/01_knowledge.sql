Виды стипендий
Государственная академическая стипендия назначается студентам очной формы на бюджетных местах по итогам сессии. Государственная социальная стипендия назначается студентам из категорий, перечисленных в законе об образовании. Повышенная академическая стипендия — за особые достижения в учёбе, науке, общественной, творческой или спортивной деятельности.

Кто получает академическую стипендию
Академическую стипендию получает студент на бюджетном месте, который сдал сессию вовремя, без задолженностей, на «хорошо» и «отлично». В первом семестре первого курса её получают все студенты-бюджетники очной формы. Размер стипендии устанавливает вуз; актуальную сумму уточните в деканате.

Социальная стипендия
Чтобы получать социальную стипендию, подайте заявление в деканат и приложите справку из органа социальной защиты населения. Справку нужно обновлять раз в год. Стипендия назначается с месяца, в котором вы принесли справку, и выплачивается независимо от оценок, если нет задолженностей.

Материальная помощь
Студент на бюджетном месте может раз в семестр попросить материальную помощь в трудной ситуации: болезнь, рождение ребёнка, потеря имущества, тяжёлое положение семьи. Подайте в кабинете заявку «Материальная помощь», коротко опишите ситуацию и приложите подтверждающие документы. Заявки рассматривает стипендиальная комиссия раз в месяц.

